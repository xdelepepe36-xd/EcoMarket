applied = missed = 0
for fname, pairs in EDITS.items():
    path = TPL + "\\" + fname
    s = io.open(path, encoding="utf-8").read()
    for old, new in pairs:
        if old in s:
            s = s.replace(old, new, 1)
            applied += 1
        else:
            print("MISS", fname, old[:60])
            missed += 1
    io.open(path, "w", encoding="utf-8", newline="\n").write(s)
